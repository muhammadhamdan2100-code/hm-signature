-- Claim a batch for delivery. SKIP LOCKED means two overlapping worker invocations
-- can never hand out the same row, and the status flip makes the claim durable.
create or replace function public.claim_email_batch(p_limit integer default 10)
returns setof public.email_outbox
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_limit is null or p_limit < 1 then
    p_limit := 1;
  end if;
  if p_limit > 50 then
    p_limit := 50;
  end if;

  return query
  with picked as (
    select e.id
    from public.email_outbox e
    where e.status in ('pending', 'failed')
      and e.next_attempt_at <= now()
    order by e.created_at
    for update of e skip locked
    limit p_limit
  )
  update public.email_outbox e
  set status = 'sending',
      attempts = e.attempts + 1,
      updated_at = now()
  from picked
  where e.id = picked.id
  returning e.*;
end;
$$;

-- Record the outcome. Error text is truncated and is expected to be a transport
-- reason, never a credential or a payload dump.
create or replace function public.finish_email_send(
  p_id bigint,
  p_status text,
  p_error text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_status not in ('sent', 'failed', 'skipped') then
    raise exception 'Unsupported email outcome.';
  end if;

  update public.email_outbox e
  set status = p_status,
      sent_at = case when p_status = 'sent' then now() else e.sent_at end,
      last_error = left(nullif(trim(coalesce(p_error, '')), ''), 300),
      -- Exponential backoff capped at six hours; a permanent failure simply stops
      -- being claimed once attempts run out.
      next_attempt_at = case
        when p_status = 'failed' then now() + (least(power(2.0, e.attempts)::int, 360) * interval '1 minute')
        else e.next_attempt_at
      end,
      updated_at = now()
  where e.id = p_id
    -- Only a row this worker still holds may be finished.
    and e.status = 'sending';
end;
$$;

-- Staff-facing queue health, used by the admin notification centre. Runs as the
-- caller on purpose: row level security then decides who sees any count at all,
-- so a customer simply gets zero rows.
create or replace function public.get_email_queue_stats()
returns table (queue_status text, row_count bigint, oldest_pending timestamptz)
language sql
stable
set search_path = public, pg_temp
as $$
  select e.status, count(*)::bigint, min(e.created_at) filter (where e.status in ('pending', 'failed'))
  from public.email_outbox e
  group by e.status
  order by e.status;
$$;

alter function public.claim_email_batch(integer) owner to postgres;
alter function public.finish_email_send(bigint, text, text) owner to postgres;
alter function public.get_email_queue_stats() owner to postgres;

-- Never callable from the browser: the worker uses the service-role connection
-- (which owns the objects, so RLS and these grants do not apply to it) and staff
-- read the queue through the table policy instead.
revoke execute on function public.claim_email_batch(integer) from public, anon, authenticated;
revoke execute on function public.finish_email_send(bigint, text, text) from public, anon, authenticated;
revoke execute on function public.get_email_queue_stats() from public, anon, authenticated;
grant execute on function public.get_email_queue_stats() to authenticated;

comment on table public.email_outbox is
  'Transactional email queue written by business-event triggers and drained by api/email-worker. Never holds credentials; promotional campaigns do not use this table.';
comment on column public.email_outbox.event_key is
  'Idempotency key: one queue row per business event occurrence, so retried requests and re-firing triggers cannot double-send.';
comment on column public.email_outbox.recipient_kind is
  'customer = stored address validated by check constraint; staff = resolved by the worker from STORE_CONTACT_EMAIL.';
