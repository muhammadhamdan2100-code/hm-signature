create or replace function public.emaillify_order_insert() returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.enqueue_email(
    'order_confirmation:' || new.order_number,
    'order_confirmation',
    'customer',
    new.customer_email,
    'HM Signature — order ' || new.order_number || ' received',
    jsonb_build_object(
      'orderNumber', new.order_number,
      'customerName', new.customer_name,
      'total', new.total,
      'paymentMethod', new.payment_method,
      'shippingCity', coalesce(new.shipping_address ->> 'city', '')
    ),
    new.order_number
  );

  perform public.enqueue_email(
    'admin_new_order:' || new.order_number,
    'admin_new_order',
    'staff',
    null,
    'New order ' || new.order_number || ' — ' || coalesce(new.payment_method, 'payment pending'),
    jsonb_build_object(
      'orderNumber', new.order_number,
      'customerName', new.customer_name,
      'total', new.total,
      'paymentMethod', new.payment_method
    ),
    new.order_number
  );

  return new;
end;
$$;

create or replace function public.emaillify_order_update() returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_currency text := 'PKR';
begin
  -- Payment confirmation: only when the payment state actually reaches Paid.
  if new.payment_status is distinct from old.payment_status
     and lower(new.payment_status) in ('paid', 'verified', 'confirmed') then
    perform public.enqueue_email(
      'payment_confirmation:' || new.order_number,
      'payment_confirmation',
      'customer',
      new.customer_email,
      'HM Signature — payment confirmed for ' || new.order_number,
      jsonb_build_object(
        'orderNumber', new.order_number,
        'customerName', new.customer_name,
        'total', new.total,
        'paymentMethod', new.payment_method
      ),
      new.order_number
    );
  end if;

  -- Order progress. Each status produces its own event key, so a later repeat of
  -- the same status never re-sends.
  if new.status is distinct from old.status then
    case lower(new.status)
      when 'confirmed', 'processing' then
        perform public.enqueue_email(
          'order_processing:' || new.order_number || ':' || new.status,
          'order_processing',
          'customer',
          new.customer_email,
          'HM Signature — preparing order ' || new.order_number,
          jsonb_build_object('orderNumber', new.order_number, 'customerName', new.customer_name, 'status', new.status),
          new.order_number
        );
      when 'shipped', 'out for delivery' then
        perform public.enqueue_email(
          'order_shipped:' || new.order_number || ':' || coalesce(new.tracking_id, 'no-tracking'),
          'order_shipped',
          'customer',
          new.customer_email,
          'HM Signature — order ' || new.order_number || ' is on its way',
          jsonb_build_object(
            'orderNumber', new.order_number,
            'customerName', new.customer_name,
            'courier', coalesce(new.courier_name, 'our delivery team'),
            'trackingId', coalesce(new.tracking_id, ''),
            'trackingUrl', coalesce(new.tracking_url, ''),
            'estimatedDelivery', coalesce(to_char(new.estimated_delivery, 'DD Mon YYYY'), '')
          ),
          new.order_number
        );
      when 'delivered' then
        perform public.enqueue_email(
          'order_delivered:' || new.order_number,
          'order_delivered',
          'customer',
          new.customer_email,
          'HM Signature — order ' || new.order_number || ' delivered',
          jsonb_build_object('orderNumber', new.order_number, 'customerName', new.customer_name),
          new.order_number
        );
        -- Review request is a separate event with its own key so it can be
        -- scheduled independently and never duplicates the delivery notice.
        perform public.enqueue_email(
          'review_request:' || new.order_number,
          'review_request',
          'customer',
          new.customer_email,
          'How does ' || coalesce(new.customer_name, 'your') || ', does the scent feel like yours?',
          jsonb_build_object('orderNumber', new.order_number, 'customerName', new.customer_name),
          new.order_number
        );
      when 'cancelled' then
        perform public.enqueue_email(
          'order_cancelled:' || new.order_number,
          'order_cancelled',
          'customer',
          new.customer_email,
          'HM Signature — order ' || new.order_number || ' cancelled',
          jsonb_build_object(
            'orderNumber', new.order_number,
            'customerName', new.customer_name,
            'total', new.total,
            'paymentMethod', new.payment_method
          ),
          new.order_number
        );
      else
        null;
    end case;
  end if;

  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Refund events
-- ---------------------------------------------------------------------------

create or replace function public.emaillify_refund_update() returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text;
  v_number text;
  v_name text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  select o.customer_email, o.order_number, o.customer_name
    into v_email, v_number, v_name
  from public.orders o
  where o.id = new.order_id;

  if v_email is null then
    return new;
  end if;

  if lower(new.status) = 'processed' then
    perform public.enqueue_email(
      'refund_processed:' || new.id::text,
      'refund_processed',
      'customer',
      v_email,
      'HM Signature — refund of ' || new.amount::text || ' for ' || coalesce(v_number, ''),
      jsonb_build_object(
        'orderNumber', coalesce(v_number, ''),
        'customerName', coalesce(v_name, ''),
        'amount', new.amount,
        'currency', new.currency,
        'reference', coalesce(new.refund_reference, '')
      ),
      v_number
    );
  elsif lower(new.status) in ('failed', 'rejected') then
    perform public.enqueue_email(
      'refund_failed:' || new.id::text,
      'refund_failed',
      'customer',
      v_email,
      'HM Signature — refund could not be completed for ' || coalesce(v_number, ''),
      jsonb_build_object(
        'orderNumber', coalesce(v_number, ''),
        'customerName', coalesce(v_name, ''),
        'amount', new.amount,
        'reason', left(coalesce(new.notes, ''), 300)
      ),
      v_number
    );
  end if;

  return new;
end;
$$;

create or replace function public.emaillify_refund_insert() returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.enqueue_email(
    'admin_refund_requested:' || new.id::text,
    'admin_refund_requested',
    'staff',
    null,
    'Refund requested on ' || coalesce(new.refund_reference, new.id::text),
    jsonb_build_object('amount', new.amount, 'currency', new.currency, 'reason', left(coalesce(new.reason, ''), 200)),
    null
  );
  return new;
end;
$$;

