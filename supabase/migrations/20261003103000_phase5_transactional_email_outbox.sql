-- Phase 5: server-side transactional email pipeline (outbox pattern).
--
-- Business events write a queue row; nothing is sent from the browser. A worker
-- claims rows, renders an approved template and delivers it over SMTP. The design
-- goals are the ones the task list calls for: server-side only, validated
-- recipients, duplicate-send prevention, retry with backoff, failure logging
-- without secret material, and a clean separation from promotional campaigns.
--
-- Authorisation follows the existing pattern in this project: the enqueue
-- functions run as the table owner (SECURITY DEFINER, pinned search_path) because
-- they fire from triggers on INSERT/UPDATE, and the queue itself is readable only
-- by staff under row level security.

create table if not exists public.email_outbox (
  id bigint generated by default as identity primary key,
  -- One queue row per business event occurrence. Inserting the same key twice is
  -- a no-op, so a retried request or a re-firing trigger cannot double-send.
  event_key text not null,
  template text not null check (template in (
    'order_confirmation',
    'payment_confirmation',
    'order_processing',
    'order_shipped',
    'order_delivered',
    'order_cancelled',
    'refund_processed',
    'refund_failed',
    'review_request',
    'abandoned_cart',
    'admin_new_order',
    'admin_payment_verified',
    'admin_refund_requested'
  )),
  recipient_kind text not null default 'customer' check (recipient_kind in ('customer', 'staff')),
  -- Customer mail always carries its own address; staff mail is resolved by the
  -- worker from the deployment's configured inbox, so no address is duplicated
  -- into rows.
  recipient_email text,
  subject text not null,
  payload jsonb not null default '{}'::jsonb,
  order_ref text,
  status text not null default 'pending' check (status in ('pending', 'sending', 'sent', 'failed', 'skipped')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint email_outbox_event_unique unique (event_key),
  constraint email_outbox_recipient_check check (
    (recipient_kind = 'customer' and coalesce(recipient_email, '') ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')
    or (recipient_kind = 'staff')
  ),
  constraint email_outbox_attempts_check check (attempts >= 0 and attempts <= 25)
);

create index if not exists idx_email_outbox_claim
  on public.email_outbox (status, next_attempt_at);
create index if not exists idx_email_outbox_order
  on public.email_outbox (order_ref);

alter table public.email_outbox enable row level security;

-- Staff can read the queue (admin visibility + audit trail) but never write it
-- through the API: only the trigger functions and the worker change rows.
drop policy if exists "Staff Read Email Outbox" on public.email_outbox;
create policy "Staff Read Email Outbox" on public.email_outbox
  for select to authenticated
  using (public.is_staff(auth.uid()));

-- ---------------------------------------------------------------------------
-- Enqueue helper
-- ---------------------------------------------------------------------------

create or replace function public.enqueue_email(
  p_event_key text,
  p_template text,
  p_recipient_kind text,
  p_recipient_email text,
  p_subject text,
  p_payload jsonb,
  p_order_ref text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  -- Whitespace-only or over-long keys are bugs, not data: refuse quietly rather
  -- than writing an unusable queue row.
  if p_event_key is null or length(trim(p_event_key)) = 0 or length(p_event_key) > 200 then
    return;
  end if;
  if p_subject is null or length(trim(p_subject)) = 0 then
    return;
  end if;

  insert into public.email_outbox (
    event_key, template, recipient_kind, recipient_email, subject, payload, order_ref
  )
  values (
    trim(p_event_key),
    p_template,
    p_recipient_kind,
    nullif(trim(coalesce(p_recipient_email, '')), ''),
    left(p_subject, 150),
    coalesce(p_payload, '{}'::jsonb),
    p_order_ref
  )
  on conflict (event_key) do nothing;
exception
  -- A queue write must never break the business transaction that caused it: a bad
  -- address format or a duplicate event key is a logging problem, not a reason to
  -- fail a sale. Stagnation is visible in the admin queue view instead.
  when others then
    null;
end;
$$;

alter function public.enqueue_email(text, text, text, text, text, jsonb, text) owner to postgres;
revoke execute on function public.enqueue_email(text, text, text, text, text, jsonb, text) from public, anon, authenticated;

