// Turns the authored catalog translations into an idempotent SQL upsert script.
//
// Content translation rows must be written by an authorized staff session in the running
// app; this script exists so the same rows can also be prepared and reviewed as SQL for a
// one-off load. It only ever touches content_translations — no product, category, order or
// stock row is referenced in a write position.
//
//   node scripts/build-content-sql.mjs

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "tmp-i18n", "content-translations.sql");

const SOURCES = ["tmp-i18n/content.ar-ur.json", "tmp-i18n/content.fr-es.json", "tmp-i18n/content.de.json"];
const ENTITY_OF = { products: "product", categories: "category", collections: "collection", notes: "fragrance_note" };

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

const rows = [];
const problems = [];

for (const file of SOURCES) {
  const path = join(ROOT, file);
  if (!existsSync(path)) {
    problems.push(`${file}: not written yet`);
    continue;
  }
  let data;
  try {
    data = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    problems.push(`${file}: invalid JSON (${error.message})`);
    continue;
  }
  for (const [language, entities] of Object.entries(data)) {
    if (!["ar", "fr", "es", "ur", "de"].includes(language)) {
      problems.push(`${file}: unexpected language "${language}"`);
      continue;
    }
    for (const [group, byId] of Object.entries(entities)) {
      const kind = ENTITY_OF[group];
      if (!kind) {
        problems.push(`${file}: unexpected entity group "${group}"`);
        continue;
      }
      for (const [id, fields] of Object.entries(byId)) {
        const clean = {};
        for (const [key, value] of Object.entries(fields ?? {})) {
          if (typeof value === "string" && value.trim()) clean[key] = value.trim();
        }
        if (Object.keys(clean).length === 0) {
          problems.push(`${file}: ${language}/${kind}/${id} has no usable field`);
          continue;
        }
        rows.push({ language, kind, id, payload: clean });
      }
    }
  }
}

const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const badRefs = rows.filter((row) => !uuid.test(row.id)).map((row) => row.id);
if (badRefs.length) problems.push(`non-uuid entity refs: ${badRefs.slice(0, 5).join(", ")}`);

// Two sources could both describe the same entity+language; the last one would silently win.
const seen = new Map();
for (const row of rows) {
  const key = `${row.language}:${row.kind}:${row.id}`;
  if (seen.has(key)) problems.push(`duplicate bundle for ${key}`);
  seen.set(key, row);
}

const sql = [
  "-- Generated by scripts/build-content-sql.mjs — do not edit by hand.",
  "-- Idempotent: re-running replaces the same bundles rather than adding rows.",
  "begin;",
  ...rows.map(
    (row) =>
      `insert into public.content_translations (entity_type, entity_ref, language_code, payload, updated_at)
 values (${q(row.kind)}, ${q(row.id)}, ${q(row.language)}, ${q(JSON.stringify(row.payload))}::jsonb, now())
 on conflict (entity_type, entity_ref, language_code)
   do update set payload = excluded.payload, updated_at = now();`
  ),
  "commit;",
  "",
].join("\n");

writeFileSync(OUT, sql, "utf8");

const byLanguage = rows.reduce((acc, row) => ({ ...acc, [row.language]: (acc[row.language] ?? 0) + 1 }), {});
console.log(`wrote ${rows.length} translation bundle(s) -> ${OUT.replace(`${ROOT}/`, "")}`);
console.log("per language:", JSON.stringify(byLanguage));
if (problems.length) {
  console.log("PROBLEMS:");
  for (const problem of problems) console.log(`  - ${problem}`);
}
